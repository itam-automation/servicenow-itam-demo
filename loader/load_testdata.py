#!/usr/bin/env python3
"""Lädt die Testdaten der Muster AG über die Import Set API in die PDI.

Jede CSV-Datei geht in ihre Staging-Tabelle; ServiceNow wendet sofort die
zugehörige Transform Map an (Definitionen in loader/staging.py):

1. Stammdaten: Standorte, Abteilungen, Benutzer, Modelle (Coalesce, also
   ohne Dubletten bei wiederholtem Lauf).
2. Geräte: zuerst der Inventar-Export, dann der Netzwerk-Scan. Das
   Transformskript übergibt jede Zeile an die IRE; sie entscheidet anhand der
   Hardware Rule, ob ein Gerät neu ist oder schon existiert.
3. Software (SAM): Softwaremodelle mit Softwarepaketen je Version,
   Installationen auf den Geräten, Lizenzen. Nach dem Lizenzimport berechnet
   ServiceNow die Lizenzposition neu (Script Include «ItamLicensePosition»).

Das Ergebnis jedes Laufs steht in loader/output/last_run.json und wird gegen
testdata/output/ground_truth.json abgeglichen.

Aufruf aus dem Projektordner:
    python3 loader/load_testdata.py                    # alles
    python3 loader/load_testdata.py --step masterdata  # nur Stammdaten
    python3 loader/load_testdata.py --step sam         # nur Software, Installationen, Lizenzen
    python3 loader/load_testdata.py --limit 3          # je Datei/Quelle nur 3 Zeilen
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from sn_client import SNClient, SNError  # noqa: E402
from staging import BY_KEY, SAM, Staging, parse_staging_row, payload, read_fields  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "testdata" / "output"
OUT_FILE = Path(__file__).resolve().parent / "output" / "last_run.json"
MASTERDATA = ("locations", "departments", "users", "models")
SOURCES = {"inventory": "Inventar-Export", "scan": "Netzwerk-Scan"}


def read_csv(name: str, data_dir: Path) -> list[dict]:
    with (data_dir / f"{name}.csv").open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


DONE_STATES = ("processed", "processed_with_errors", "error", "cancelled")


def import_rows(client: SNClient, staging: Staging, rows: list[dict], label: str,
                timeout: int = 1800) -> tuple[str, list[dict]]:
    """Lädt alle Zeilen als ein Import Set, wartet auf den Transform und liest das Ergebnis je Zeile."""
    if not rows:
        return "", []
    response = client.request("POST", f"/api/now/import/{staging.table}/insertMultiple",
                              body={"records": [payload(row, staging) for row in rows]})
    import_set_id = response["import_set_id"]
    started = time.monotonic()
    while True:
        import_set = client.get_records("sys_import_set", f"sys_id={import_set_id}", "number,state")[0]
        done = client.count(staging.table, f"sys_import_set={import_set_id}^sys_import_state!=pending")
        print(f"  {label}: {import_set['number']} {import_set['state']}, {done}/{len(rows)} Zeilen",
              end="\r", flush=True)
        if import_set["state"] in DONE_STATES and done == len(rows):
            break
        if time.monotonic() - started > timeout:
            raise SNError(0, f"{import_set['number']} nach {timeout} s nicht fertig")
        time.sleep(5)
    print()
    staged = client.get_records(staging.table, f"sys_import_set={import_set_id}", read_fields(staging))
    source_of = {row.get("source_id", ""): row.get("source", "") for row in rows}
    results = [{"file": staging.key, "import_set": import_set["number"],
                **parse_staging_row(r, staging)} for r in staged]
    for r in results:
        r["source"] = source_of.get(r["key"], "")
    return import_set["number"], results


def compare_with_ground_truth(results: list[dict], ground_truth: dict) -> list[str]:
    ci_of = {r["key"]: r.get("ire_ci", "") for r in results if r["file"] == "devices"}
    by_type: dict[str, Counter] = defaultdict(Counter)
    for issue in ground_truth["issues"]:
        if "duplicate_of" not in issue or issue["source_id"] not in ci_of:
            continue
        dup, orig = ci_of[issue["source_id"]], ci_of.get(issue["duplicate_of"])
        by_type[issue["type"]]["zusammengeführt" if dup and dup == orig else "eigene CI"] += 1
    return [f"    {kind}: " + ", ".join(f"{n} {v}" for v, n in c.items()) for kind, c in by_type.items()]


RUN_REPORT = ROOT / "docs" / "import_run.md"


def write_run_report(results: list[dict], duplicates: list[str]) -> None:
    """Zusammenfassung eines vollständigen Laufs als Nachweis (ohne sys_ids und Instanz-URL)."""
    lines = [
        "# Import run",
        "",
        f"Full run on {datetime.now():%Y-%m-%d} via the Import Set API (`insertMultiple`), one import set per file. "
        "Generated by `python3 loader/load_testdata.py`.",
        "",
        "| Import set | Staging table | Target | Rows | Result |",
        "|---|---|---|---:|---|",
    ]
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in results:
        groups[(r["import_set"], r["file"])].append(r)
    for (number, key), rows in groups.items():
        staging = BY_KEY[key]
        if key == "devices":
            source = rows[0]["source"]
            outcome = Counter(r.get("ire_operation") or r["status"] for r in rows)
            target = f"IRE ({source})"
        else:
            outcome = Counter(r["status"] for r in rows)
            target = staging.target
        result = ", ".join(f"{n} {k}" for k, n in sorted(outcome.items()))
        lines.append(f"| {number} | `{staging.table}` | {target} | {len(rows)} | {result} |")
    findings = Counter(part.split(":", 1)[0].strip() for r in results if r["file"] == "devices"
                       for part in r.get("dq_findings", "").split(";") if part.strip())
    if findings:
        lines += ["", "Import check on the source data (column `u_dq_findings`, report «ITAM DQ 8»):", ""]
        lines += [f"- {code}: {n} rows" for code, n in sorted(findings.items())]
    if duplicates:
        lines += ["", "Duplicates from the network scan (compared with `ground_truth.json`):", ""]
        lines += [f"- {d.strip()}" for d in duplicates]
    RUN_REPORT.parent.mkdir(exist_ok=True)
    RUN_REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Lädt die Testdaten der Muster AG über Import Sets in die PDI.")
    parser.add_argument("--step", choices=("all", "masterdata", "devices", "sam"), default="all")
    parser.add_argument("--source", choices=("all", "inventory", "scan"), default="all",
                        help="nur eine Gerätequelle (Scan erst nach dem Inventar, sonst entstehen Dubletten)")
    parser.add_argument("--limit", type=int, default=None, help="höchstens so viele Zeilen je Datei bzw. Quelle")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    args = parser.parse_args(argv)

    client = SNClient.from_env()
    print(f"Instanz {client.base_url}, Benutzer {client.user}, Import Set API")
    results: list[dict] = []
    comparison: list[str] = []

    if args.step in ("all", "masterdata"):
        for key in MASTERDATA:
            staging = BY_KEY[key]
            rows = read_csv(key, args.data_dir)[:args.limit]
            _, res = import_rows(client, staging, rows, f"{staging.table} -> {staging.target}")
            results += res
            print("    " + ", ".join(f"{n} {s}" for s, n in Counter(r["status"] for r in res).items()))

    if args.step in ("all", "devices"):
        staging = BY_KEY["devices"]
        devices = read_csv("devices", args.data_dir)
        chosen = SOURCES.values() if args.source == "all" else [SOURCES[args.source]]
        for source in chosen:
            rows = [d for d in devices if d["source"] == source][:args.limit]
            _, res = import_rows(client, staging, rows, f"{staging.table} ({source}) -> IRE")
            results += res
            ops = Counter(r.get("ire_operation") or r["status"] for r in res)
            print("    IRE: " + ", ".join(f"{n} {op}" for op, n in sorted(ops.items())))
            flagged = sum(1 for r in res if r.get("dq_findings"))
            print(f"    Importprüfung: {flagged} Zeilen mit Befund")
        ground_truth = json.loads((args.data_dir / "ground_truth.json").read_text(encoding="utf-8"))
        comparison = compare_with_ground_truth(results, ground_truth)
        if comparison:
            print("  Dubletten aus dem Netzwerk-Scan:")
            print("\n".join(comparison))

    if args.step in ("all", "sam"):
        for key in SAM:
            staging = BY_KEY[key]
            rows = read_csv(key, args.data_dir)[:args.limit]
            _, res = import_rows(client, staging, rows, f"{staging.table} -> {staging.target}")
            results += res
            print("    " + ", ".join(f"{n} {s}" for s, n in Counter(r["status"] for r in res).items()))

    errors = [r for r in results if r["status"] == "error" or "Fehler:" in r.get("message", "")]
    missing = [r for r in results if r.get("ire_missing")]
    if errors:
        print(f"  Fehler: {len(errors)}, zum Beispiel {errors[0]['key']}: {errors[0]['message'][:200]}")
    if missing:
        print(f"  Zeilen mit nicht auflösbaren Referenzen: {len(missing)}")

    if args.step == "all" and args.source == "all" and args.limit is None:
        write_run_report(results, comparison)
        print(f"Nachweis: {RUN_REPORT.relative_to(ROOT)}")

    OUT_FILE.parent.mkdir(exist_ok=True)
    OUT_FILE.write_text(json.dumps({
        "run_at": datetime.now().isoformat(timespec="seconds"),
        "args": {k: str(v) for k, v in vars(args).items()},
        "import_sets": sorted({r.get("import_set", "") for r in results} - {""}),
        "rows": results,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Ergebnis: {OUT_FILE.relative_to(ROOT)}")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
